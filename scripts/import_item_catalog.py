"""Convert a pinned upstream checkout into the bundled read-only catalog.

Usage: python scripts/import_item_catalog.py docs/internal/catalog-upstream
Only parses Python AST literals and JSON; never imports or executes upstream code.
"""
import ast
import argparse
import csv
import hashlib
import json
from pathlib import Path
import subprocess

PIN = "d47f5898c4c9ea1b8722098363330eae623c7d9e"
WORKSPACE = Path(__file__).resolve().parent.parent


def rust_string(value):
    hashes = "#"
    while '"' + hashes in value:
        hashes += "#"
    return 'r' + hashes + '"' + value + '"' + hashes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", nargs="?", default=WORKSPACE / "docs/internal/catalog-upstream")
    source = Path(parser.parse_args().source).resolve()
    revision = subprocess.check_output(
        ["git", "-C", str(source), "rev-parse", "HEAD"], text=True
    ).strip()
    if revision != PIN:
        raise ValueError("Upstream revision differs from the reviewed pin")
    lookup_path = source / "core/lookup.py"
    index_path = source / "data/item/item_name_index.json"
    weapon_path = source / "data/weapon/all_weapon_part_EN.csv"
    constants = {}
    roots = []
    for node in ast.parse(lookup_path.read_text(encoding="utf-8-sig")).body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if not isinstance(target, ast.Name):
            continue
        if isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            constants[target.id] = node.value.value
        if target.id == "ID_MAP":
            for key, value in zip(node.value.keys, node.value.values):
                manufacturer, family = (constants[item.id] for item in key.elts)
                roots.append((ast.literal_eval(value), family, manufacturer))
    roots.sort()
    if not roots or len({row[0] for row in roots}) != len(roots):
        raise ValueError("Missing or duplicate root records")
    index = json.loads(index_path.read_text(encoding="utf-8-sig"))
    parts_by_key = {}
    for reference, record in index["part_refs"].items():
        fields = reference.split(":")
        name = (record.get("name") or {}).get("en", "").strip()
        if len(fields) != 2 or not all(field.isdecimal() for field in fields):
            continue
        root, part = map(int, fields)
        if not 0 <= root <= 0xffffffff or not 0 <= part <= 0xffff:
            raise ValueError("Out-of-range catalog key")
        category = record.get("category") or None
        parts_by_key[root, part] = {
            "name": name or None,
            "category": record.get("display_group") or category,
            "internal": record.get("part") or None,
            "naming_role": category,
            "rarity": record.get("rarity") or None,
            "unique_accessory": category == "barrel_acc" and any(
                tag.startswith("uni_") for tag in record.get("weapon_tags", [])
            ),
        }
    seen_weapon_keys = set()
    with weapon_path.open(encoding="utf-8-sig", newline="") as stream:
        for row in csv.DictReader(stream):
            root = int(row["Manufacturer & Weapon Type ID"])
            part = int(row["Part ID"])
            key = root, part
            if key in seen_weapon_keys or not 0 <= root <= 0xffffffff or not 0 <= part <= 0xffff:
                raise ValueError("Duplicate or out-of-range weapon part key")
            seen_weapon_keys.add(key)
            record = parts_by_key.setdefault(key, {"name": None, "naming_role": None,
                "rarity": None, "unique_accessory": False})
            # Preserve name-index titles; CSV supplies fallback metadata.
            record["name"] = record["name"] or row["Name"].strip() or None
            record["category"] = row["Part Type"].strip() or None
            record["internal"] = row["String"].strip() or None
    parts = sorted(parts_by_key.items())
    if not parts:
        raise ValueError("Missing part records")
    lines = [
        "// Generated by scripts/import_item_catalog.py; do not edit by hand.",
        "// Upstream: SuperExboom / Borderlands4-SaveEditor; AGPL-3.0.",
        "use super::{ItemCatalog, PartRecord, RootRecord};",
        "pub static CATALOG: ItemCatalog<'static> = ItemCatalog {",
        'game_version: "upstream snapshot ' + PIN[:12] + '; game build unverified",',
        "roots: &[",
    ]
    for root, family, manufacturer in roots:
        lines.append(f"RootRecord {{ root_id: {root}, family: {rust_string(family)}, manufacturer: Some({rust_string(manufacturer)}) }},")
    lines.append("], parts: &[")
    def optional(value):
        return f"Some({rust_string(value)})" if value else "None"
    for (root, part), record in parts:
        lines.append(f"PartRecord {{ root_id: {root}, part_index: {part}, display_name: {optional(record['name'])}, category: {optional(record['category'])}, internal_name: {optional(record['internal'])}, naming_role: {optional(record['naming_role'])}, rarity: {optional(record['rarity'])}, unique_accessory: {str(record['unique_accessory']).lower()} }},")
    lines.extend([
        "] };",
    ])
    output = WORKSPACE / "crates/bl4-core/src/save/item_catalog_data.rs"
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    subprocess.run(["rustfmt", "--edition", "2024", str(output)], check=True)
    license_target = WORKSPACE / "resources/catalog/LICENSE.upstream.txt"
    license_target.parent.mkdir(parents=True, exist_ok=True)
    license_target.write_bytes((source / "LICENSE").read_bytes())
    metadata = {
        "manifest_version": 1,
        "resources": [{
            "path": "crates/bl4-core/src/save/item_catalog_data.rs",
            "source": "https://github.com/superexboom/Borderlands4-SaveEditor",
            "revision": PIN,
            "schema": "RootRecord and PartRecord; optional English name, category, internal identifier, naming role, rarity and unique-accessory flag",
            "conversion": "AST literal ID_MAP; numeric part_refs merged with English weapon CSV by root and part ID; name-index titles and naming roles retained",
            "license": "AGPL-3.0; see resources/catalog/LICENSE.upstream.txt",
            "game_build": None,
            "source_folder": index.get("source_folder"),
            "roots": len(roots), "parts": len(parts),
            "named_parts": sum(bool(record["name"]) for _, record in parts),
            "sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
            "inputs": [{"path": str(path.relative_to(source)).replace("\\", "/"),
                        "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
                       for path in [lookup_path, index_path, weapon_path]],
        }],
    }
    (WORKSPACE / "resources/manifest.json").write_text(
        json.dumps(metadata, indent=2) + "\n", encoding="utf-8"
    )
    print(f"Imported {len(roots)} roots and {len(parts)} part records at {PIN}")


if __name__ == "__main__":
    main()
